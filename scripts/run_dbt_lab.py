def write(relative, content):
    target = PROJECT / relative
    target.parent.mkdir(parents=True, exist_ok=True)
    target.write_text(content.strip() + '\n', encoding='utf-8')


def run(label, *args, allow_failure=False):
    started = time.perf_counter()
    result = subprocess.run(['uv', 'run', 'dbt', *args], cwd=PROJECT,
                            text=True, stdout=subprocess.PIPE, stderr=subprocess.STDOUT)
    (EVIDENCE / f'{label}.txt').write_text(chr(10).join(line.rstrip() for line in result.stdout.splitlines()).rstrip()+chr(10), encoding='utf-8')
    RESULTS[label] = {'exit_code': result.returncode, 'seconds': round(time.perf_counter()-started, 3)}
    for name in ('run_results.json', 'manifest.json'):
        source = PROJECT / 'target' / name
        if source.exists() and name == 'run_results.json':
            shutil.copyfile(source, EVIDENCE / f'{label}-results.json')
    print(f'{label}: exit={result.returncode}', flush=True)
    if result.returncode and not allow_failure:
        print(result.stdout[-5000:], flush=True)
        raise RuntimeError(f'{label} failed; inspect evidence')
    return result


def query(label, sql, params=None):
    with duckdb.connect(str(PROJECT / 'lab_medallion.duckdb')) as con:
        con.execute("SET TimeZone='UTC'")
        result = con.execute(sql, params or {})
        columns = [item[0] for item in result.description]
        rows = [dict(zip(columns, row)) for row in result.fetchall()]
    (EVIDENCE / f'{label}.json').write_text(json.dumps(rows, indent=2, default=str) + '\n', encoding='utf-8')
    return rows


